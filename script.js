const modal = document.getElementById("propertyModal");
const mainImage = document.getElementById("mainGalleryImage");
const galleryThumbs = document.getElementById("galleryThumbs");
const galleryCounter = document.getElementById("galleryCounter");
let activeProperty = 0;
let activePhoto = 0;
let previousFocus = null;

function showPhoto(index) {
  const property = properties[activeProperty];
  activePhoto = (index + property.gallery.length) % property.gallery.length;
  const photo = property.gallery[activePhoto];
  mainImage.src = photo.src;
  mainImage.alt = photo.alt;
  galleryCounter.textContent = `${activePhoto + 1} / ${property.gallery.length}`;
  [...galleryThumbs.querySelectorAll("button")].forEach((button, i) => {
    button.classList.toggle("active", i === activePhoto);
    button.setAttribute("aria-pressed", i === activePhoto ? "true" : "false");
  });
}

function openProperty(index, trigger) {
  activeProperty = Number(index);
  activePhoto = 0;
  previousFocus = trigger || document.activeElement;
  const property = properties[activeProperty];
  document.getElementById("modalType").textContent = property.type;
  document.getElementById("modalTitle").textContent = property.title;
  document.getElementById("modalLocation").textContent =
    `⌖  ${property.location}`;
  document.getElementById("modalPrice").textContent = property.price;
  document.getElementById("modalAddress").textContent = property.address;
  const facts = document.getElementById("modalFacts");
  facts.innerHTML = "";
  property.facts.forEach(([label, value]) => {
    const item = document.createElement("div");
    item.className = "fact-item";
    const labelEl = document.createElement("span");
    labelEl.textContent = label;
    const valueEl = document.createElement("strong");
    valueEl.textContent = value;
    item.append(labelEl, valueEl);
    facts.appendChild(item);
  });
  galleryThumbs.innerHTML = "";
  property.gallery.forEach((photo, i) => {
    const button = document.createElement("button");
    button.type = "button";
    button.className = "gallery-thumb";
    button.setAttribute("aria-label", `Lihat foto ${i + 1}: ${photo.alt}`);
    button.addEventListener("click", () => showPhoto(i));
    const image = document.createElement("img");
    image.src = photo.src;
    image.alt = "";
    button.appendChild(image);
    galleryThumbs.appendChild(button);
  });
  showPhoto(0);
  modal.classList.add("is-open");
  modal.setAttribute("aria-hidden", "false");
  document.body.classList.add("modal-open");
  document.getElementById("modalClose").focus();
}

function closeModal() {
  modal.classList.remove("is-open");
  modal.setAttribute("aria-hidden", "true");
  document.body.classList.remove("modal-open");
  if (previousFocus && typeof previousFocus.focus === "function")
    previousFocus.focus();
}

